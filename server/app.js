require('dotenv').config();
const express = require('express');
const http = require('http');
const path = require('path');
const helmet = require('helmet');
const cors = require('cors');
const rateLimit = require('express-rate-limit');
const { Server } = require('socket.io');
const connectDB = require('./config/db');
const app = express();
const server = http.createServer(app);
const io = new Server(server, { cors: { origin: process.env.CLIENT_ORIGIN || true } });
app.set('io', io);
io.on('connection', socket => socket.on('join:shop', shopId => { if (/^[a-f\d]{24}$/i.test(shopId)) socket.join(`shop:${shopId}`); }));
app.use(helmet({ contentSecurityPolicy: false }));
app.use(cors({ origin: process.env.CLIENT_ORIGIN || true }));
app.use(express.json({ limit: '20kb' }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: true, legacyHeaders: false }));
app.use(express.static(path.join(__dirname, '../client')));
app.get('/api/health', (req, res) => res.json({ status: 'ok', service: 'QueueWise API' }));
app.use('/api/auth', require('./routes/auth'));
app.use('/api/shops', require('./routes/shops'));
app.use('/api/queue', require('./routes/queue'));
app.get('*', (req, res) => res.sendFile(path.join(__dirname, '../client/index.html')));
app.use((err, req, res, next) => { console.error(err); res.status(err.status || 500).json({ message: err.message || 'Something went wrong.' }); });
const PORT = process.env.PORT || 3000;
connectDB().then(() => server.listen(PORT, () => console.log(`QueueWise running at http://localhost:${PORT}`))).catch(err => { console.error('Startup failed:', err.message); process.exit(1); });
